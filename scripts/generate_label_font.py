"""Offline Noto Sans outline extraction; requires the locally installed fontTools."""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

root = Path(__file__).resolve().parents[1]
font = TTFont(root / 'apps/slicer-gui/assets/fonts/NotoSans-Variable.ttf')
glyphs = font.getGlyphSet()
scale = font['head'].unitsPerEm

class Pen(BasePen):
    def __init__(self):
        super().__init__(glyphs)
        self.rings = []
    def _moveTo(self, p):
        self.rings.append([p])
    def _lineTo(self, p):
        self.rings[-1].append(p)
    def _qCurveToOne(self, b, c):
        a = self._getCurrentPoint()
        # Uniform subdivisions of the true quadratic; no pixel cells.
        for i in range(1, 4):
            t = i / 3
            self._lineTo(tuple((1-t)**2*a[j]+2*t*(1-t)*b[j]+t*t*c[j] for j in (0, 1)))
    def _closePath(self):
        if self.rings[-1][-1] == self.rings[-1][0]:
            self.rings[-1].pop()
    def _endPath(self):
        pass

out = ['// SPDX-License-Identifier: OFL-1.1',
       '// Generated by scripts/generate_label_font.py from bundled Noto Sans.',
       '// License: apps/slicer-gui/assets/fonts/OFL.txt. Coordinates in em units.',
       '#[allow(clippy::approx_constant)] // Font coordinates, not mathematical constants.',
       'pub(crate) fn glyph(c: u8) -> (f64, Vec<Vec<[f64; 2]>>) {', '    match c {']
for c in range(32, 127):
    name = font.getBestCmap()[c]
    pen = Pen()
    glyphs[name].draw(pen)
    rings = ','.join('vec![' + ','.join(f'[{x/scale:.6f},{y/scale:.6f}]' for x,y in r) + ']' for r in pen.rings)
    out.append(f'        {c} => ({font["hmtx"][name][0]/scale:.6f}, vec![{rings}]),')
out += ['        _ => (0.0, Vec::new()),', '    }', '}']
(root / 'libs/print-glue/src/label_font.rs').write_text('\n'.join(out)+'\n', newline='\n')
