"""Prepare the product pictures shown beside the printer and resin pickers.

Usage: python scripts/dev/product_pictures.py <dir of generated PNGs>

The input holds square renders named `printer_<profile id>.png` and
`resin_<profile id>.png` (transparent background). Each is cropped to its
visible pixels, centred on a square with a small margin so every picture has
the same scale, resized to 192 px, and written to
`apps/slicer-gui/assets/pictures/<printer|resin>/<id>.png`. The embedded list
`apps/slicer-gui/src/product_pictures_list.rs` is then regenerated from every
picture present. Needs Pillow.
"""
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GUI = os.path.join(ROOT, 'apps', 'slicer-gui')
OUT = os.path.join(GUI, 'assets', 'pictures')
SIZE = 192
MARGIN = 0.06


def prepare(src, dst):
    im = Image.open(src).convert('RGBA')
    # Visible pixels only: ignore the faint contact shadow when framing.
    alpha = im.getchannel('A').point(lambda a: 255 if a > 40 else 0)
    box = alpha.getbbox() or (0, 0, im.width, im.height)
    im = im.crop(box)
    side = int(max(im.size) * (1 + 2 * MARGIN))
    square = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    square.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    square.resize((SIZE, SIZE), Image.LANCZOS).save(dst, optimize=True)


def main():
    src_dir = sys.argv[1]
    for name in sorted(os.listdir(src_dir)):
        if not name.endswith('.png') or '_' not in name:
            continue
        kind, pid = name[:-4].split('_', 1)
        if kind not in ('printer', 'resin'):
            continue
        os.makedirs(os.path.join(OUT, kind), exist_ok=True)
        prepare(os.path.join(src_dir, name), os.path.join(OUT, kind, pid + '.png'))
    rows = []
    for kind in ('printer', 'resin'):
        folder = os.path.join(OUT, kind)
        for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
            pid = name[:-4]
            rows.append(f'    ("{kind}", "{pid}", include_bytes!("../assets/pictures/{kind}/{name}")),')
    with open(os.path.join(GUI, 'src', 'product_pictures_list.rs'), 'w', encoding='utf8', newline='\n') as f:
        f.write('// Generated by scripts/dev/product_pictures.py; do not edit.\n[\n' + '\n'.join(rows) + '\n]\n')
    print(f'{len(rows)} pictures')


if __name__ == '__main__':
    main()
